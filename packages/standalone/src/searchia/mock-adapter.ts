import type { SearchiaLanguage } from "./i18n";
/**
 * Mock & Real Searchia Chat Adapters
 * ----------------------------------
 * Provides an explicitly labeled mock adapter for local testing and UI verification,
 * and an unconfigured SearchiaApiAdapter placeholder ready for real backend integration.
 */

import type {
  SearchiaChatAdapter,
  SendMessageOptions,
  SuggestedQuestionItem,
} from "./types";

/**
 * EXPLICITLY LABELED MOCK ADAPTER
 * --------------------------------
 * Simulates a conversational AI search assistant for Searchia Agent Studio.
 * Does not make external network requests or invent fake API endpoints/tokens.
 */
export class MockSearchiaAdapter implements SearchiaChatAdapter {
  readonly name = "MockSearchiaAdapter";
  readonly isMock = true;

  private delayMs: number;

  constructor(options: { delayMs?: number } = {}) {
    this.delayMs = options.delayMs ?? 25;
  }

  async getSuggestedQuestions(
    language: SearchiaLanguage = "fa",
  ): Promise<SuggestedQuestionItem[]> {
    if (language === "fa")
      return [
        { id: "q1", question: "سرچیا چیست؟" },
        { id: "q2", question: "چطور ویجت را در وب‌سایت قرار دهم؟" },
        { id: "q3", question: "آیا پاسخ‌ها از Markdown پشتیبانی می‌کنند؟" },
      ];
    return [
      {
        id: "q1",
        question: "What is Searchia Agent Studio?",
      },
      {
        id: "q2",
        question: "How do I embed Searchia chat on my website?",
      },
      {
        id: "q3",
        question: "Does Searchia support streaming markdown answers?",
      },
    ];
  }

  async sendMessage(options: SendMessageOptions): Promise<string> {
    const { prompt, onChunk, signal } = options;
    const responseText = this.generateResponse(
      prompt,
      options.language ?? "fa",
    );

    // Simulate progressive streaming of the response
    const words = responseText.split(" ");
    let accumulated = "";

    for (let i = 0; i < words.length; i++) {
      if (signal?.aborted) {
        throw new DOMException("Operation aborted by user", "AbortError");
      }

      const word = words[i];
      accumulated += (i === 0 ? "" : " ") + word;

      if (onChunk) {
        onChunk(word, accumulated);
      }

      // Small delay between tokens to simulate realistic streaming
      await new Promise((resolve) => setTimeout(resolve, this.delayMs));
    }

    return accumulated;
  }

  async sendFeedback(messageId: string, vote: 1 | 0): Promise<void> {
    // In mock mode, log feedback to console for verification
    console.info(
      `[MockSearchiaAdapter] Feedback recorded: message "${messageId}" received ${
        vote === 1 ? "👍 (thumbs up)" : "👎 (thumbs down)"
      }`,
    );
  }

  private generateResponse(prompt: string, language: SearchiaLanguage): string {
    if (language === "fa") {
      const note = "\n\n*این پاسخ نمایشی است و از API واقعی دریافت نشده است.*";
      if (/ویجت|وب‌سایت|embed|website/i.test(prompt))
        return (
          'برای افزودن ویجت، فایل‌های CSS و JavaScript را بارگذاری و سپس آن را راه‌اندازی کنید:\n\n```javascript\nSearchiaChat.init({ language: "fa" });\n```\n\nویجت بدون iframe اجرا می‌شود.' +
          note
        );
      if (/markdown|کد|جریان|stream/i.test(prompt))
        return (
          "بله، پاسخ‌های نمایشی از **Markdown** پشتیبانی می‌کنند:\n\n- متن **پررنگ** و *مورب*\n- فهرست‌ها و کد مانند `const language = 'fa';`\n- بلوک کد با دکمهٔ کپی\n\n```javascript\nSearchiaChat.init({ language: \"fa\" });\n```" +
          note
        );
      return (
        "**دستیار سرچیا**\n\nاین نسخه، نمونهٔ نمایشی یک دستیار گفت‌وگویی است. می‌توانید سؤال بپرسید و نمایش تدریجی پاسخ، کپی کد و بازخورد را امتحان کنید.\n\nاتصال به سرویس واقعی هنوز پیاده‌سازی نشده است." +
        note
      );
    }
    const lower = prompt.toLowerCase();

    if (lower.includes("what is searchia") || lower.includes("agent studio")) {
      return (
        "**Searchia Agent Studio** is an AI-powered conversational search platform designed to give your users direct, accurate answers from your organization's content.\n\n" +
        "### Key Capabilities:\n" +
        "- **Conversational Search**: Synthesizes results into natural, actionable answers.\n" +
        "- **Framework Agnostic**: Embeds via vanilla JavaScript without iframes.\n" +
        "- **Custom Knowledge**: Grounded directly on your indexed documents.\n\n" +
        "*(Note: This response is generated by the `MockSearchiaAdapter` for UI verification.)*"
      );
    }

    if (
      lower.includes("embed") ||
      lower.includes("website") ||
      lower.includes("how do i")
    ) {
      return (
        "Embedding the Searchia AI chat widget into any website requires just a script and stylesheet:\n\n" +
        "```html\n" +
        "<!-- 1. Include Searchia styles and script -->\n" +
        '<link rel="stylesheet" href="searchia-chat.min.css" />\n' +
        '<script src="searchia-chat.min.js"></script>\n\n' +
        "<!-- 2. Initialize the widget -->\n" +
        "<script>\n" +
        "  SearchiaChat.init({\n" +
        '    container: "#chat-widget",\n' +
        '    buttonText: "Ask Searchia",\n' +
        "  });\n" +
        "</script>\n" +
        "```\n\n" +
        "No `<iframe>` or heavy frameworks required! It mounts directly to the DOM with its UI runtime bundled."
      );
    }

    if (lower.includes("markdown") || lower.includes("streaming")) {
      return (
        "Yes! Searchia renders rich GitHub-flavored Markdown with safe HTML sanitization:\n\n" +
        "1. **Bold** and *italic* formatting\n" +
        "2. Ordered and unordered lists\n" +
        "3. Inline code like `const query = 'search';`\n" +
        "4. Code blocks with one-click copy buttons\n" +
        "5. Sanitized links: [Searchia Documentation](https://searchia.ir)\n\n" +
        '```javascript\nSearchiaChat.init({ language: "en" });\n```\n\nAll streamed token-by-token in real-time. These are simulated responses.'
      );
    }

    return (
      `Thank you for asking about **"${prompt}"**!\n\n` +
      "I am currently operating with the **MockSearchiaAdapter** in Searchia's proof-of-concept widget.\n\n" +
      "Real API integration has not been implemented in this demo.\n\n" +
      "> **Mock Adapter Status**: Active • Streaming Verified • Feedback Enabled"
    );
  }
}

/**
 * SEARCHIA AGENT API ADAPTER (STUB)
 * ---------------------------------
 * Placeholder for connecting to the official Searchia Agent Studio API
 * once endpoint contracts, streaming protocols (SSE), and authentication
 * mechanisms are provided.
 */
export interface SearchiaApiConfig {
  /** The Searchia API base URL or Agent Studio endpoint */
  endpoint?: string;
  /** Public API key or publishable token (do NOT expose secret keys in client-side code) */
  apiKey?: string;
  /** Agent or Assistant identifier */
  agentId?: string;
}

export class SearchiaApiAdapter implements SearchiaChatAdapter {
  readonly name = "SearchiaApiAdapter";
  readonly isMock = false;

  private config: SearchiaApiConfig;

  constructor(config: SearchiaApiConfig = {}) {
    this.config = config;
  }

  async sendMessage(_options: SendMessageOptions): Promise<string> {
    if (!this.config.endpoint && !this.config.agentId) {
      throw new Error(
        "[SearchiaApiAdapter] Searchia Agent API configuration is missing. " +
          "Please configure endpoint and agentId, or use MockSearchiaAdapter for testing.",
      );
    }

    // This stub will be implemented once the official Searchia Agent API contract is available.
    throw new Error(
      "[SearchiaApiAdapter] Not implemented: awaiting Searchia Agent API specification.",
    );
  }

  async getSuggestedQuestions(
    _language: SearchiaLanguage = "fa",
  ): Promise<SuggestedQuestionItem[]> {
    return [];
  }

  async sendFeedback(messageId: string, vote: 1 | 0): Promise<void> {
    console.info(
      `[SearchiaApiAdapter] Feedback stub called for ${messageId} with vote ${vote}`,
    );
  }
}
